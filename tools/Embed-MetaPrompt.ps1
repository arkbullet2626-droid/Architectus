# Generates src/Architectus/Generated/SecretPrompt.g.cs for official builds.
#
# The official "Architect" meta-prompt is NOT in this repository. In CI it arrives through
# the ARCHITECTUS_META_PROMPT repository secret; this script encrypts it (AES-256) into a
# generated C# file that is compiled into the app and never committed (see .gitignore).
#
# If the secret is absent (forks, local builds), nothing is generated and the app uses the
# open baseline prompt in Services/MetaPrompt.cs.
#
# Honest note: anything a program can decrypt on your PC can, with effort, be recovered by
# someone determined. This keeps the tuned prompt out of the public source and out of plain
# sight in the binary; it is not DRM.

$ErrorActionPreference = 'Stop'
$prompt = $env:ARCHITECTUS_META_PROMPT
$outDir = Join-Path $PSScriptRoot '..\src\Architectus\Generated'
$outFile = Join-Path $outDir 'SecretPrompt.g.cs'

if ([string]::IsNullOrWhiteSpace($prompt)) {
    Write-Host 'ARCHITECTUS_META_PROMPT not set: building with the open baseline meta-prompt.'
    if (Test-Path $outFile) { Remove-Item $outFile }
    exit 0
}

$plain = [System.Text.Encoding]::UTF8.GetBytes($prompt.Trim())
$aes = [System.Security.Cryptography.Aes]::Create()
$aes.KeySize = 256
$aes.GenerateKey()
$aes.GenerateIV()
$cipher = $aes.EncryptCbc($plain, $aes.IV, [System.Security.Cryptography.PaddingMode]::PKCS7)

# Light mask on the stored key so it isn't a plain AES key sitting next to the data.
$sha = [System.Security.Cryptography.SHA256]::Create()
$mask = $sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes('Architectus/Opifex'))
$k = New-Object byte[] $aes.Key.Length
for ($i = 0; $i -lt $k.Length; $i++) { $k[$i] = $aes.Key[$i] -bxor $mask[$i % $mask.Length] }

function ToCs([byte[]]$b) { ($b | ForEach-Object { '0x{0:X2}' -f $_ }) -join ',' }

New-Item -ItemType Directory -Force -Path $outDir | Out-Null
@"
// <auto-generated>Created by tools/Embed-MetaPrompt.ps1 during the official build. Do not commit.</auto-generated>
namespace Architectus.Generated;

internal static class SecretPrompt
{
    internal static readonly byte[] K = new byte[] { $(ToCs $k) };
    internal static readonly byte[] IV = new byte[] { $(ToCs $aes.IV) };
    internal static readonly byte[] Data = new byte[] { $(ToCs $cipher) };
}
"@ | Set-Content -Path $outFile -Encoding UTF8

Write-Host "Embedded official meta-prompt ($($plain.Length) bytes, encrypted)."
